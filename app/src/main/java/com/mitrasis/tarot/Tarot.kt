    val cards: List<TarotCard> by lazy {
        val list = mutableListOf<TarotCard>()
        var id = 0
        majorSource.forEach { (name, light, shadow) ->
            list += TarotCard(
                id = id++,
                title = name,
                arcana = "Старший аркан",
                light = light.split("|"),
                shadow = shadow.split("|")
            )
        }
        suits.forEach { (suit, domain, suitShadow) ->
            ranks.forEach { (rank, stage, rankShadow) ->
                list += TarotCard(
                    id = id++,
                    title = "$rank $suit",
                    arcana = "Младший аркан",
                    light = listOf(domain, stage, "сюжет: $rank, домен: $suit"),
                    shadow = listOf(suitShadow, rankShadow, "тень: $rank $suit")
                )
            }
        }
        list
    }

    fun draw(spread: Spread, seed: Long = System.nanoTime()): List<Drawn> {
        val random = Random(seed)
        val shuffled = cards.shuffled(random)
        return spread.positions.mapIndexed { index, position ->
            Drawn(
                card = shuffled[index],
                reversed = random.nextFloat() < 0.35f,
                position = position
            )
        }
    }
