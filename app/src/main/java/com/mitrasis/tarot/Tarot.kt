package com.mitrasis.tarot

import kotlin.random.Random

data class TarotCard(
    val id: Int,
    val title: String,
    val arcana: String,
    val light: List<String>,
    val shadow: List<String>
)

data class Drawn(
    val card: TarotCard,
    val reversed: Boolean,
    val position: String
) {
    val orientation: String get() = if (reversed) "перевёрнута" else "прямая"
    fun activeKeywords(): List<String> = if (reversed) card.shadow else card.light
}

data class Spread(
    val name: String,
    val hint: String,
    val positions: List<String>
)

