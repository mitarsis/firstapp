package com.mitrasis.tarot

/**
 * Схема v3: модель выбирает не карту, а ЗНАЧЕНИЕ.
 *
 * Почему так: GLiNER сопоставляет смысл вопроса со смыслом метки. Пока метка —
 * «Солнце», вопрос про Солнце всегда выигрывает, и это не ответ, а совпадение.
 * Здесь в метках нет ни одного названия карты, поэтому совпадать не с чем —
 * остаётся только смысл. Карту под выбранное значение подставляет приложение.
