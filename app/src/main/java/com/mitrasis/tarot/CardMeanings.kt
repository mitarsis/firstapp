    /** Метки и соответствующие им названия карт — параллельные списки. */
    fun candidates(suitName: String): Pair<List<String>, List<String>> {
        val labels = majors.map { it.second }.toMutableList()
        val titles = majors.map { it.first }.toMutableList()
        val suit = suits.firstOrNull { it.name == suitName }
        if (suit != null) {
            suit.ranks.forEach { (rank, meaning) ->
                labels.add(meaning)
                titles.add("$rank ${suit.name}")
            }
        }
        return labels to titles
    }
